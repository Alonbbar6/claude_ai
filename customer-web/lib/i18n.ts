const DICTS: Record<Lang, Record<MessageKey, string>> = { en, es };

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>) {
  let s = DICTS[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function formatPrice(n: number, lang: Lang) {
  return new Intl.NumberFormat(lang === "es" ? "es-US" : "en-US", { style: "currency", currency: "USD" }).format(n);
}
